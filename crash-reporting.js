#!/usr/bin/env node
"use strict";

var fs = require("fs");
var path = require("path");
var crypto = require("crypto");
const os = require("os");
const zlib = require("zlib");
const http = require("http");
const https = require("https");
const { Transform, Readable } = require("stream");
const { pipeline } = require("stream/promises");

var _debug = false;

function log(msg) {
  if (_debug) {
    console.log("[DEBUG] " + msg);
  }
}

function generateUUID() {
  var uuid = crypto.randomUUID();
  log("Generated UUID: " + uuid);
  return uuid;
}

function resolveConfig(options) {
  log("Resolving configuration...");
  var sdkKey = (options && options.sdkKey) || process.env.SDK_KEY;
  var serverUrl = (options && options.serverUrl) || process.env.SERVER_URL;

  if (sdkKey && serverUrl) {
    log("Config resolved from options/env");
    return { sdkKey: sdkKey, serverUrl: serverUrl };
  }

  var projectRoot = (options && options.projectRoot) || ".";
  var packageJsonPath = path.resolve(projectRoot, "package.json");
  log("Looking for package.json at: " + packageJsonPath);

  try {
    var pkg = JSON.parse(fs.readFileSync(packageJsonPath, "utf8"));
    var cordovaPlugins = (pkg.cordova && pkg.cordova.plugins) || {};
    var pluginVars = cordovaPlugins["cordova-plugin-dataroid-sdk"] || {};
    log("Found plugin variables: " + JSON.stringify(Object.keys(pluginVars)));

    if (!sdkKey) {
      sdkKey = pluginVars.SDK_KEY;
    }
    if (!serverUrl) {
      serverUrl = pluginVars.SERVER_URL;
    }
  } catch (e) {
    log("Could not read package.json: " + e.message);
  }

  if (!sdkKey) {
    throw new Error(
      "SDK key not found. Provide via --sdk-key, SDK_KEY env var, or cordova plugin variables in package.json",
    );
  }
  if (!serverUrl) {
    throw new Error(
      "Server URL not found. Provide via --server-url, SERVER_URL env var, or cordova plugin variables in package.json",
    );
  }

  log("Config resolved");
  return { sdkKey: sdkKey, serverUrl: serverUrl };
}

function findMapFiles(dir) {
  log("Scanning directory for .map files: " + dir);
  var results = [];
  var entries = fs.readdirSync(dir, { withFileTypes: true });
  for (var i = 0; i < entries.length; i++) {
    var entry = entries[i];
    var fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      if (entry.name !== "node_modules") {
        results = results.concat(findMapFiles(fullPath));
      } else {
        log("Skipping node_modules: " + fullPath);
      }
    } else if (entry.name.slice(-4) === ".map") {
      log("Found map file: " + fullPath);
      results.push(fullPath);
    }
  }
  return results;
}

function resolveSourcemaps(options) {
  var sourcemap = options && options.sourcemap;
  var sourcemapDir = options && options.sourcemapDir;
  log(
    "Resolving sourcemaps — file: " +
      (sourcemap || "none") +
      ", dir: " +
      (sourcemapDir || "none"),
  );

  if (sourcemap && sourcemapDir) {
    throw new Error("Cannot use --sourcemap and --sourcemap-dir together.");
  }
  if (!sourcemap && !sourcemapDir) {
    throw new Error("--sourcemap or --sourcemap-dir is required.");
  }

  if (sourcemap) {
    var resolved = path.resolve(sourcemap);
    log("Resolved single sourcemap path: " + resolved);
    if (!fs.existsSync(resolved)) {
      throw new Error("Source map file not found: " + resolved);
    }
    return [resolved];
  }

  var resolvedDir = path.resolve(sourcemapDir);
  log("Resolved sourcemap directory: " + resolvedDir);
  if (!fs.existsSync(resolvedDir)) {
    throw new Error("Source map directory not found: " + resolvedDir);
  }
  var files = findMapFiles(resolvedDir);
  log("Found " + files.length + " .map file(s)");
  if (files.length === 0) {
    throw new Error("No .map files found in " + resolvedDir);
  }
  return files;
}

function validateSourcemaps(filePaths) {
  log("Validating " + filePaths.length + " sourcemap(s)...");
  for (var i = 0; i < filePaths.length; i++) {
    var filePath = filePaths[i];
    try {
      var content = fs.readFileSync(filePath, "utf8");
      JSON.parse(content);
      log(
        "Valid JSON: " +
          path.basename(filePath) +
          " (" +
          content.length +
          " chars)",
      );
    } catch (e) {
      throw new Error(
        "Invalid JSON in source map " +
          path.basename(filePath) +
          ": " +
          e.message,
      );
    }
  }
  log("All sourcemaps validated successfully");
}

function prepare(outputDir) {
  log("Preparing UUID — output: " + (outputDir || "."));
  var uuid = generateUUID();
  var filename = "sourceMapUUID.js";
  var filePath = path.join(outputDir || ".", filename);
  var content =
    "// Auto-generated by cordova-plugin-dataroid-sdk — do not edit\n" +
    'var SOURCEMAP_UUID = "' +
    uuid +
    '";\n' +
    "if (typeof module !== 'undefined') module.exports = SOURCEMAP_UUID;\n";

  fs.writeFileSync(filePath, content, "utf8");
  log("Wrote " + content.length + " bytes to " + filePath);
  console.log("Source map UUID written to " + filePath);
  console.log("UUID: " + uuid);
  return uuid;
}

// --project-root locates the project on this machine, and is also sent to the
// server as projectRoot: the prefix of the app's own source paths in the maps,
// which are relative (e.g. "src/app.js"). The server rejects ".." and characters
// outside [a-zA-Z0-9/_.-], and an absolute local path, such as a CI checkout,
// would mark no frame as app code. Only a relative path inside the project is
// sent; anything else is replaced by ".".
var SERVER_PROJECT_ROOT_REGEX = /^[a-zA-Z0-9_.-][a-zA-Z0-9/_.-]*$/;

function serverProjectRoot(projectRoot) {
  if (
    SERVER_PROJECT_ROOT_REGEX.test(projectRoot) &&
    projectRoot.indexOf("..") === -1
  ) {
    return projectRoot;
  }
  console.warn(
    `--project-root "${projectRoot}" is used to find the project on this machine only. ` +
      `It is not a relative path inside the project, so "." is sent to the server.`,
  );
  return ".";
}

// Resolves symlinks (e.g. /var -> /private/var on macOS) so a map path and the
// working directory compare equal however each was reached.
function realPath(filePath) {
  try {
    return fs.realpathSync(filePath);
  } catch (e) {
    return path.resolve(filePath);
  }
}

function sourceFilePath(mapFilePath, workingDir) {
  var normalized = mapFilePath.replace(/\\/g, "/");
  var relativePath;
  // Prefer the path below <workingDir>/www, so a project inside a directory
  // named "www" (e.g. /var/www/app) still matches the runtime frame path.
  if (workingDir) {
    var fromWww = path
      .relative(
        realPath(path.resolve(workingDir, "www")),
        realPath(mapFilePath),
      )
      .replace(/\\/g, "/");
    if (
      fromWww &&
      fromWww !== ".." &&
      fromWww.indexOf("../") !== 0 &&
      !path.isAbsolute(fromWww)
    ) {
      relativePath = fromWww;
    }
  }
  if (relativePath === undefined) {
    var wwwIndex = normalized.indexOf("/www/");
    relativePath =
      wwwIndex !== -1
        ? normalized.substring(wwwIndex + "/www/".length)
        : path.basename(normalized);
  }
  return relativePath.slice(-4) === ".map"
    ? relativePath.slice(0, -4)
    : relativePath;
}

// A table-based CRC32 keeps the standalone CLI compatible with Node 18.
let crcTable;
const updateCrc32 = (crc, bytes) => {
  if (!crcTable) {
    crcTable = Array.from({ length: 256 }, (_, value) => {
      for (let bit = 0; bit < 8; bit++) {
        value = value & 1 ? 0xedb88320 ^ (value >>> 1) : value >>> 1;
      }
      return value >>> 0;
    });
  }
  for (const byte of bytes) crc = crcTable[(crc ^ byte) & 255] ^ (crc >>> 8);
  return crc >>> 0;
};

const removeTemporary = async (filePath, recursive = false) => {
  try {
    await fs.promises.rm(filePath, { recursive, force: true });
  } catch {
    console.warn(`Could not remove temporary source map file: ${filePath}`);
  }
};

/** Owns both files until it successfully returns the completed ZIP path. */
const createSourcemapZip = async (mapPath, entryName, signal) => {
  signal?.throwIfAborted();
  const name = Buffer.from(entryName, "utf8");
  const directory = await fs.promises.mkdtemp(
    path.join(os.tmpdir(), "dataroid-sourcemap-"),
  );
  const deflatePath = path.join(directory, "source.deflate");
  const zipPath = path.join(directory, "source.zip");
  let transferred = false;
  try {
    let crc = 0xffffffff;
    let size = 0;
    const checksum = new Transform({
      transform(chunk, encoding, callback) {
        size += chunk.length;
        if (size >= 0xffffffff)
          return callback(
            new Error("Source map exceeds the ZIP32 size limit."),
          );
        crc = updateCrc32(crc, chunk);
        callback(null, chunk);
      },
    });
    await pipeline(
      fs.createReadStream(mapPath),
      checksum,
      zlib.createDeflateRaw(),
      fs.createWriteStream(deflatePath),
      { signal },
    );
    const compressedSize = (await fs.promises.stat(deflatePath)).size;
    const localSize = 30 + name.length;
    if (compressedSize + localSize >= 0xffffffff)
      throw new Error("Source map exceeds the ZIP32 size limit.");
    crc = (crc ^ 0xffffffff) >>> 0;
    // Fixed DOS date (1980-01-01) makes the archive reproducible.
    const local = Buffer.alloc(localSize);
    local.writeUInt32LE(0x04034b50, 0);
    local.writeUInt16LE(20, 4);
    local.writeUInt16LE(0x0800, 6); // UTF-8 entry name.
    local.writeUInt16LE(8, 8);
    local.writeUInt16LE(33, 12);
    local.writeUInt32LE(crc, 14);
    local.writeUInt32LE(compressedSize, 18);
    local.writeUInt32LE(size, 22);
    local.writeUInt16LE(name.length, 26);
    name.copy(local, 30);
    const central = Buffer.alloc(46 + name.length);
    central.writeUInt32LE(0x02014b50, 0);
    central.writeUInt16LE(20, 4);
    local.copy(central, 6, 4, 30);
    name.copy(central, 46);
    const end = Buffer.alloc(22);
    end.writeUInt32LE(0x06054b50, 0);
    end.writeUInt16LE(1, 8);
    end.writeUInt16LE(1, 10);
    end.writeUInt32LE(central.length, 12);
    end.writeUInt32LE(localSize + compressedSize, 16);
    // Open the intermediate stream only as the generator reaches it. On cancellation,
    // async iteration closes it before the outer pipeline settles and cleanup runs.
    async function* archive() {
      yield local;
      for await (const chunk of fs.createReadStream(deflatePath)) yield chunk;
      yield central;
      yield end;
    }
    await pipeline(Readable.from(archive()), fs.createWriteStream(zipPath), {
      signal,
    });
    signal?.throwIfAborted();
    await removeTemporary(deflatePath);
    signal?.throwIfAborted();
    transferred = true;
    return zipPath;
  } finally {
    if (!transferred) await removeTemporary(directory, true);
  }
};

const redact = (message, secrets = []) => {
  let text = String(message);
  for (const secret of secrets) {
    if (secret) text = text.split(secret).join("[redacted]");
  }
  // Storage errors can echo the signed query separately from the full URL.
  return text
    .replace(/https?:\/\/[^\s<>"']+/gi, "[redacted URL]")
    .replace(/X-Amz-[A-Za-z-]+(?:=|%3D)[^&\s<>"']*/gi, "[redacted signature]");
};

/** Fixed-length HTTP with separate connection and socket-inactivity deadlines. */
const uploadRequest = async (
  url,
  { method, headers, body, filePath, signal, inactivityMs, secrets = [] },
) => {
  signal?.throwIfAborted();
  let parsed;
  try {
    parsed = new URL(url);
    if (
      !["http:", "https:"].includes(parsed.protocol) ||
      parsed.username ||
      parsed.password
    )
      throw new Error();
  } catch {
    throw new Error("Invalid upload URL in configuration or mint response.");
  }
  let source;
  let transfer;
  try {
    return await new Promise((resolve, reject) => {
      let request;
      let response;
      let settled = false;
      let sent = false;
      let received;
      let connectTimer;
      const cleanup = () => {
        clearTimeout(connectTimer);
        signal?.removeEventListener("abort", abort);
        request?.setTimeout(0);
      };
      const finish = (error, value) => {
        if (settled) return;
        settled = true;
        cleanup();
        if (error || !sent) {
          source?.destroy();
          response?.destroy();
          request?.destroy();
        }
        // A transfer/response error can arrive after the HTTP headers. Preserve
        // that status for diagnosis without treating a partial response as success.
        if (error && response?.statusCode) {
          reject(new Error(`${error.message} Status: ${response.statusCode}.`));
        } else if (error) reject(error);
        else resolve(value);
      };
      const abort = () => finish(new Error("Source map upload cancelled."));
      // A complete response decides the outcome. Storage answers 2xx only after
      // receiving Content-Length bytes, but the socket can close before the
      // request stream reports finish (ERR_STREAM_PREMATURE_CLOSE).
      const complete = () => {
        if (received) finish(null, received);
      };
      const connected = () => {
        if (settled) return;
        clearTimeout(connectTimer);
        request.setTimeout(inactivityMs, () =>
          finish(new Error(`${method} network inactivity timeout.`)),
        );
      };
      try {
        request = (parsed.protocol === "https:" ? https : http).request(
          parsed,
          {
            method,
            headers,
            agent: false,
          },
          (incoming) => {
            response = incoming;
            const chunks = [];
            let bytes = 0;
            incoming.on("data", (chunk) => {
              bytes += chunk.length;
              if (bytes > 65536)
                return finish(new Error(`${method} response exceeds 64 KiB.`));
              chunks.push(chunk);
            });
            incoming.on("error", (error) =>
              finish(
                new Error(
                  `${method} response interrupted (${error.code || "I/O error"}).`,
                ),
              ),
            );
            incoming.on("end", () => {
              const raw = Buffer.concat(chunks).toString("utf8");
              received = {
                status: incoming.statusCode,
                // Successful mint bodies contain a credential: return JSON privately, never log it.
                body:
                  method === "POST" &&
                  incoming.statusCode >= 200 &&
                  incoming.statusCode < 300
                    ? raw
                    : redact(raw, secrets),
              };
              complete();
            });
            // A response closed before its end never settles through "end".
            incoming.on("close", () => {
              if (!received)
                finish(new Error(`${method} response interrupted (closed).`));
            });
          },
        );
        request.on("error", (error) =>
          finish(
            new Error(
              `${method} network request failed (${error.code || "I/O error"}).`,
            ),
          ),
        );
        connectTimer = setTimeout(
          () => finish(new Error(`${method} connection timeout.`)),
          30000,
        );
        request.on("socket", (socket) => {
          socket.once(
            parsed.protocol === "https:" ? "secureConnect" : "connect",
            connected,
          );
        });
        signal?.addEventListener("abort", abort, { once: true });
        if (signal?.aborted) {
          abort();
          return;
        }
        if (filePath) {
          source = fs.createReadStream(filePath);
          // Handle rejection immediately; also await stream closure in the outer finally.
          transfer = pipeline(source, request).then(
            () => {
              sent = true;
              complete();
            },
            () => {
              // Once the response has started, its end or error settles the request.
              if (!response)
                finish(new Error(`${method} file transfer failed.`));
            },
          );
        } else {
          request.end(body, () => {
            sent = true;
            complete();
          });
        }
      } catch {
        finish(new Error(`${method} request could not be started.`));
      }
    });
  } finally {
    source?.destroy();
    await transfer;
  }
};

const mintUploadUrl = async (config, mappingId, fileName, srcPath, signal) => {
  const body = JSON.stringify({
    mappingId,
    fileName,
    framework: "CORDOVA",
    sourceFilePath: srcPath,
    ...(config.projectRoot ? { projectRoot: config.projectRoot } : {}),
  });
  const response = await uploadRequest(
    `${config.serverUrl.replace(/\/+$/, "")}/crash-service/upload-url/sourcemap`,
    {
      method: "POST",
      headers: {
        "x-appconnect-sdk-key": config.sdkKey,
        "Content-Type": "application/json",
        Accept: "application/json",
        "Content-Length": Buffer.byteLength(body),
      },
      body,
      signal,
      inactivityMs: 30000,
      secrets: [config.sdkKey],
    },
  );
  if (response.status === 409) return { kind: "already-uploaded" };
  if (response.status < 200 || response.status >= 300) {
    // Older Dataroid servers do not provide the presigned upload endpoint.
    const hint =
      response.status === 404 || response.status === 405
        ? " Check the server URL. If it is correct, the server may not support presigned source map uploads yet; contact Dataroid support."
        : "";
    throw new Error(
      `Upload URL request failed. Status: ${response.status}.${hint} Response: ${response.body}`,
    );
  }
  let value;
  try {
    value = JSON.parse(response.body);
  } catch {
    throw new Error("Invalid JSON in upload URL response.");
  }
  if (!value || typeof value.url !== "string" || !value.url.trim())
    throw new Error("Missing upload URL in mint response.");
  if (
    typeof value.expiresAt !== "string" ||
    !Number.isFinite(Date.parse(value.expiresAt))
  ) {
    throw new Error("Missing or invalid expiresAt in mint response.");
  }
  if (
    typeof value.uploadId !== "string" ||
    !/^[A-Za-z0-9-]+$/.test(value.uploadId)
  ) {
    throw new Error("Missing or invalid uploadId in mint response.");
  }
  return {
    kind: "ok",
    uploadId: value.uploadId,
    url: value.url,
    expiresAt: value.expiresAt,
  };
};

/**
 * @param {string} url - Presigned storage URL returned by mintUploadUrl
 * @param {string} zipPath - Path to the ZIP file to upload
 * @param {AbortSignal} [signal]
 * @param {string} [credentialForRedaction] - Redacted from errors; never sent as a header
 */
const putSourcemapZip = async (
  url,
  zipPath,
  signal,
  credentialForRedaction,
) => {
  const size = (await fs.promises.stat(zipPath)).size;
  const response = await uploadRequest(url, {
    method: "PUT",
    headers: { "Content-Type": "application/zip", "Content-Length": size },
    filePath: zipPath,
    signal,
    inactivityMs: 300000,
    secrets: [url, credentialForRedaction],
  });
  if (response.status < 200 || response.status >= 300) {
    throw new Error(
      `Direct upload failed. Status: ${response.status}. Response: ${response.body}`,
    );
  }
};

// One mint and one single-entry ZIP per source file, as required by the Cordova contract.
async function uploadOneFile(
  filePath,
  serverUrl,
  sdkKey,
  uuid,
  projectRoot,
  signal,
) {
  const config = { serverUrl, sdkKey, projectRoot };
  const fileName = path.basename(filePath);
  let zipPath;
  try {
    const result = await mintUploadUrl(
      config,
      uuid,
      fileName + ".zip",
      sourceFilePath(filePath, process.cwd()),
      signal,
    );
    if (result.kind === "already-uploaded") {
      console.log("  Already uploaded and processed: " + fileName);
      return;
    }
    log(
      `Upload URL received. uploadId: ${result.uploadId} expiresAt: ${result.expiresAt}`,
    );
    zipPath = await createSourcemapZip(filePath, fileName, signal);
    if (Date.parse(result.expiresAt) <= Date.now())
      throw new Error("Upload URL expired. Run the upload command again.");
    await putSourcemapZip(result.url, zipPath, signal, sdkKey);
    console.log(
      `  Uploaded ${fileName}. uploadId: ${result.uploadId}. Validation and indexing continue asynchronously on the server.`,
    );
  } catch (error) {
    throw new Error(
      "Upload failed for " + fileName + ": " + redact(error.message, [sdkKey]),
    );
  } finally {
    if (zipPath) await removeTemporary(path.dirname(zipPath), true);
  }
}

function upload(options) {
  log("Starting upload");
  var config = resolveConfig(options);
  var sdkKey = config.sdkKey;
  var serverUrl = config.serverUrl;
  var projectRoot = (options && options.projectRoot) || ".";
  var serverRoot = serverProjectRoot(projectRoot);

  var uuidDir = options.outputDir || projectRoot;
  var uuidFile = path.resolve(uuidDir, "sourceMapUUID.js");
  log("Reading UUID from: " + uuidFile);
  var uuidContent = fs.readFileSync(uuidFile, "utf8");
  var uuidMatch = uuidContent.match(
    /[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}/i,
  );
  if (!uuidMatch) {
    throw new Error("Could not extract UUID from " + uuidFile);
  }
  var uuid = uuidMatch[0];
  log("Extracted UUID: " + uuid);

  var files = options.sourcemapFiles || resolveSourcemaps(options);
  validateSourcemaps(files);

  for (var i = 0; i < files.length; i++) {
    var stat = fs.statSync(files[i]);
    console.log("  " + path.basename(files[i]) + " (" + stat.size + " bytes)");
  }

  // A failed file does not stop the others, as in the other Dataroid uploaders.
  // The run still fails at the end. Cancellation stops it at once.
  var failed = [];
  var chain = Promise.resolve();
  for (var j = 0; j < files.length; j++) {
    (function (filePath) {
      chain = chain.then(function () {
        return uploadOneFile(
          filePath,
          serverUrl,
          sdkKey,
          uuid,
          serverRoot,
          options.signal,
        ).catch(function (error) {
          if (
            files.length === 1 ||
            (options.signal && options.signal.aborted)
          ) {
            throw error;
          }
          console.error(error.message);
          failed.push(path.basename(filePath));
        });
      });
    })(files[j]);
  }

  return chain.then(function () {
    if (failed.length > 0) {
      throw new Error(
        failed.length +
          " of " +
          files.length +
          " source map(s) failed: " +
          failed.join(", ") +
          ". Fix the errors above and run the command again; source maps that are already processed are skipped.",
      );
    }
    console.log(
      files.length +
        " source map(s) delivered or already processed. New uploads are validated and indexed asynchronously.",
    );
  });
}

function setDebug(enabled) {
  _debug = enabled;
}

if (require.main === module) {
  var args = process.argv.slice(2);

  if (args.indexOf("--debug") !== -1) {
    _debug = true;
    args.splice(args.indexOf("--debug"), 1);
  }

  var command = args[0];

  log("CLI invoked — command: " + command);

  function getArg(name) {
    var idx = args.indexOf(name);
    return idx !== -1 && idx + 1 < args.length ? args[idx + 1] : null;
  }

  if (!command || (command !== "prepare" && command !== "upload")) {
    console.error("Usage: dataroid-crash-reporting <prepare|upload> [options]");
    console.error("");
    console.error("Commands:");
    console.error("  prepare [flags]       Generate source map UUID");
    console.error("  upload  [flags]       Upload source map(s)");
    console.error("");
    console.error("Prepare flags:");
    console.error(
      "  --output-dir <dir>   Directory to write sourceMapUUID.js (default: .)",
    );
    console.error("");
    console.error("Upload flags:");
    console.error("  --sourcemap <file>       Single .map file to upload");
    console.error(
      "  --sourcemap-dir <dir>    Directory to scan for .map files (recursive)",
    );
    console.error(
      "  --output-dir <dir>       Directory containing sourceMapUUID.js (default: .)",
    );
    console.error(
      "  --project-root <path>    Project folder (default: .); sent to the server only if relative",
    );
    console.error("  --sdk-key <key>          SDK key (or SDK_KEY env var)");
    console.error(
      "  --server-url <url>       Server URL (or SERVER_URL env var)",
    );
    console.error("");
    console.error("General flags:");
    console.error("  --debug                  Enable verbose debug logging");
    process.exit(1);
  }

  if (command === "prepare") {
    prepare(getArg("--output-dir") || ".");
  } else if (command === "upload") {
    const controller = new AbortController();
    let exitSignal;
    const onInterrupt = () => {
      exitSignal = 130;
      controller.abort();
    };
    const onTerminate = () => {
      exitSignal = 143;
      controller.abort();
    };
    process.once("SIGINT", onInterrupt);
    process.once("SIGTERM", onTerminate);
    const cleanup = () => {
      process.removeListener("SIGINT", onInterrupt);
      process.removeListener("SIGTERM", onTerminate);
      if (exitSignal) process.exitCode = exitSignal;
    };
    try {
      upload({
        signal: controller.signal,
        sourcemap: getArg("--sourcemap"),
        sourcemapDir: getArg("--sourcemap-dir"),
        sdkKey: getArg("--sdk-key"),
        serverUrl: getArg("--server-url"),
        outputDir: getArg("--output-dir"),
        projectRoot: getArg("--project-root") || ".",
      })
        .catch(function (err) {
          console.error(err.message);
          process.exitCode = 1;
        })
        .finally(cleanup);
    } catch (err) {
      console.error(err.message);
      process.exitCode = 1;
      cleanup();
    }
  }
}

